#!/usr/bin/env bash
# Assemble a build tree for examples/leveldb/brix.py.
#
# brix globs have no exclusion, but leveldb's library .cc files sit in db/,
# table/, util/, helpers/ interleaved with *_test.cc, benchmarks, and the
# Windows port. So we stage exactly the POSIX library sources — the list
# parsed straight out of the upstream CMakeLists.txt, so it stays faithful as
# leveldb evolves — as symlinks under build-src/lib/ (symlinks, so editing a
# real .cc still re-stales its compile). Headers are read in place via -I., so
# the depfiles brix scans point back at leveldb's real tree.
#
#   examples/leveldb/setup.sh            # stage into ~/Projects/brix_test/leveldb
#   python examples/leveldb/brix.py build
#
# Override the checkout with BRIX_LEVELDB_ROOT.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${BRIX_LEVELDB_ROOT:-$HOME/Projects/brix_test/leveldb}"

if [ ! -f "$ROOT/CMakeLists.txt" ]; then
  echo "leveldb checkout not found at $ROOT" >&2
  echo "clone it first: git clone --depth 1 https://github.com/google/leveldb.git \"$ROOT\"" >&2
  exit 1
fi

cd "$ROOT"

# The library's PRIVATE .cc sources, as listed in add_library(leveldb ...),
# stopping at the PUBLIC headers. Plus the POSIX env (the Windows one is
# selected by CMake's WIN32 branch, which we are not on).
mapfile -t SOURCES < <(
  awk '/add_library\(leveldb ""\)/,/VERSION_GREATER/' CMakeLists.txt \
    | grep -oE '"[^"]+\.cc"' | tr -d '"'
  echo "util/env_posix.cc"       # CMake's non-WIN32 branch
  echo "helpers/memenv/memenv.cc" # added to the target in a later block
)

echo "staging ${#SOURCES[@]} library sources into build-src/lib/"
rm -rf build-src
for src in "${SOURCES[@]}"; do
  dest="build-src/lib/$src"
  mkdir -p "$(dirname "$dest")"
  ln -sf "$ROOT/$src" "$dest"
done

# port/port_config.h is pulled in by port_stdcxx.h via __has_include; CMake
# generates it from port_config.h.in. These are the values for POSIX Linux
# with no optional compression/crc libraries linked in.
mkdir -p build-src/config/port
cat > build-src/config/port/port_config.h <<'EOF'
// Generated by examples/leveldb/setup.sh (stands in for CMake's configure_file
// of port/port_config.h.in). Values for POSIX Linux, no snappy/zstd/crc32c.
#ifndef STORAGE_LEVELDB_PORT_PORT_CONFIG_H_
#define STORAGE_LEVELDB_PORT_PORT_CONFIG_H_
#define HAVE_FDATASYNC 1
#define HAVE_FULLFSYNC 0
#define HAVE_O_CLOEXEC 1
#define HAVE_CRC32C 0
#define HAVE_SNAPPY 0
#define HAVE_ZSTD 0
#endif  // STORAGE_LEVELDB_PORT_PORT_CONFIG_H_
EOF

# The smoke program (kept in the example dir, versioned with brix) links
# against the finished archive.
mkdir -p smoke
cp "$HERE/main.cc" smoke/main.cc

echo "done. now: python $HERE/brix.py build && python $HERE/brix.py smoke"
