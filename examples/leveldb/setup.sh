#!/usr/bin/env bash
# One-time setup for examples/leveldb/brix.py. The library sources are
# globbed straight from leveldb's tree by brix.py (with `-` excludes for
# tests, benchmarks, and the Windows port) — nothing is staged. Two files
# still have to exist inside the workspace:
#
#   gen/config/port/port_config.h — CMake normally configure_file()s this
#     from port_config.h.in; port_stdcxx.h pulls it in via __has_include.
#   smoke/main.cc — the smoke program, versioned with brix in the example
#     dir, copied in so the workspace-rooted glob can see it.
#
#   examples/leveldb/setup.sh            # into ~/Projects/brix_test/leveldb
#   python examples/leveldb/brix.py build
#
# Override the checkout with BRIX_LEVELDB_ROOT.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="${BRIX_LEVELDB_ROOT:-$HOME/Projects/brix_test/leveldb}"

if [ ! -f "$ROOT/CMakeLists.txt" ]; then
  echo "leveldb checkout not found at $ROOT" >&2
  echo "clone it first: git clone --depth 1 https://github.com/google/leveldb.git \"$ROOT\"" >&2
  exit 1
fi

cd "$ROOT"

# A leftover staging tree from the pre-exclusion version of this example
# would double every library source in brix.py's globs.
rm -rf build-src

# Values for POSIX Linux with no optional compression/crc libraries.
mkdir -p gen/config/port
cat > gen/config/port/port_config.h <<'EOF'
// Generated by examples/leveldb/setup.sh (stands in for CMake's configure_file
// of port_config.h.in). Values for POSIX Linux, no snappy/zstd/crc32c.
#ifndef STORAGE_LEVELDB_PORT_PORT_CONFIG_H_
#define STORAGE_LEVELDB_PORT_PORT_CONFIG_H_
#define HAVE_FDATASYNC 1
#define HAVE_FULLFSYNC 0
#define HAVE_O_CLOEXEC 1
#define HAVE_CRC32C 0
#define HAVE_SNAPPY 0
#define HAVE_ZSTD 0
#endif  // STORAGE_LEVELDB_PORT_PORT_CONFIG_H_
EOF

# The smoke program links against the finished archive.
mkdir -p smoke
cp "$HERE/main.cc" smoke/main.cc

echo "done. now: python $HERE/brix.py build && python $HERE/brix.py run smoke"
