//! Embed the top-level `assets/` tree into the engine at build time.
//!
//! An `asset` atom names a brix-shipped helper by a logical POSIX path; the
//! engine owns the bytes so a frontend can reference the helper portably
//! (docs/asset-engine.md). This generates `EMBEDDED: &[(&str, &[u8])]` — the
//! logical name paired with its bytes via `include_bytes!` — so the compiled
//! library carries every helper with nothing external to ship. Paths are
//! absolute (computed here) so they resolve regardless of where the generated
//! file lands in `OUT_DIR`. A helper edit re-triggers the build via the
//! per-file `rerun-if-changed`, keeping the embedded digest current.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    // rust/brix-core -> repo root -> assets
    let assets_dir = manifest
        .join("..")
        .join("..")
        .join("assets")
        .canonicalize()
        .expect("assets/ tree must exist at the repo root (docs/asset-engine.md)");

    let mut entries: Vec<(String, PathBuf)> = Vec::new();
    collect(&assets_dir, &assets_dir, &mut entries);
    entries.sort();

    let mut out = String::from("// @generated by build.rs — embedded asset table.\n");
    out.push_str("pub static EMBEDDED: &[(&str, &[u8])] = &[\n");
    for (name, path) in &entries {
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!(
            "    ({:?}, include_bytes!({:?})),\n",
            name,
            path.display().to_string()
        ));
    }
    out.push_str("];\n");

    println!("cargo:rerun-if-changed={}", assets_dir.display());
    println!("cargo:rerun-if-changed=build.rs");
    let out_path = PathBuf::from(env::var("OUT_DIR").unwrap()).join("assets_embed.rs");
    fs::write(&out_path, out).unwrap();
}

/// Collect every file under `dir` as (logical POSIX name relative to `root`,
/// absolute path), recursing into subdirectories.
fn collect(root: &Path, dir: &Path, out: &mut Vec<(String, PathBuf)>) {
    for entry in fs::read_dir(dir).unwrap() {
        let path = entry.unwrap().path();
        if path.is_dir() {
            collect(root, &path, out);
        } else if path.is_file() {
            let rel = path.strip_prefix(root).unwrap();
            out.push((rel.to_string_lossy().replace('\\', "/"), path));
        }
    }
}
