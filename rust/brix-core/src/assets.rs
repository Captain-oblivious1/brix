//! The asset store (Rust engine half). Mirror of `src/brix/assets.py`.
//!
//! An `asset` atom names a brix-shipped helper by a stable logical `name`
//! (POSIX, brix-relative). This store is the engine-side authority the name
//! resolves against: it owns the bytes (embedded at build time by `build.rs`),
//! hands render an absolute path, and hands fingerprinting a **content digest
//! that is a function of the bytes alone** — never the resolved path, so it is
//! identical across machines and across the Python/TS frontends
//! (docs/asset-engine.md, docs/boundary-schema.md).
//!
//! The Python engine mirrors this exactly; the two must agree on both the set
//! of shipped names and each name's digest. That cross-engine identity is the
//! soundness-critical invariant — the digest here is the same sha256-hex of the
//! bytes that `src/brix/assets.py` computes and that the change detector
//! computes for a `file` atom, so an asset edit re-stales exactly like a source
//! edit.

use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

// EMBEDDED: &[(&str, &[u8])] — logical name -> bytes, generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/assets_embed.rs"));

/// The bytes shipped under `name`, or `None` if the store does not ship it.
pub fn bytes(name: &str) -> Option<&'static [u8]> {
    EMBEDDED.iter().find(|(n, _)| *n == name).map(|(_, b)| *b)
}

fn sha256_hex(data: &[u8]) -> String {
    let mut hasher = Sha256::new();
    hasher.update(data);
    let mut hex = String::with_capacity(64);
    for b in hasher.finalize() {
        hex.push_str(&format!("{:02x}", b));
    }
    hex
}

/// sha256 hex of the asset's bytes — byte-only (no path, no mtime), so it is
/// identical on every machine and in the Python engine. An unshipped name is a
/// loud error before anything runs.
pub fn digest(name: &str) -> Result<String, String> {
    bytes(name)
        .map(sha256_hex)
        .ok_or_else(|| format!("asset not shipped: {name}"))
}

/// The engine-internal root under which assets materialize for rendering. Kept
/// **outside** any workspace so a materialized helper (e.g. a `.java` file)
/// can never be swept into a source glob, and content-addressed so it is shared
/// and stable across builds. The rendered path is not fingerprint material
/// (docs/asset-engine.md §3-B), so this location is a free, engine-private
/// choice — a later change to co-locate it under the build cache root would need
/// no fingerprint regen.
pub fn default_cache_root() -> PathBuf {
    std::env::temp_dir().join("brix-assets")
}

/// [`resolve_path`] using [`default_cache_root`] — the form render uses.
pub fn resolve(name: &str) -> Result<PathBuf, String> {
    resolve_path(name, &default_cache_root())
}

/// The absolute filesystem path a command line names for this asset. The bytes
/// are materialized into a content-addressed location under `cache_root`
/// (`<cache_root>/assets/<digest>/<name>`) on first use — idempotent, and the
/// rendered path is deliberately **not** fingerprint material (it differs per
/// machine, exactly like a resolved `tool` path). Write-then-rename keeps a
/// concurrent reader from seeing a torn file; concurrent writers write
/// identical bytes.
pub fn resolve_path(name: &str, cache_root: &Path) -> Result<PathBuf, String> {
    let data = bytes(name).ok_or_else(|| format!("asset not shipped: {name}"))?;
    let dest = cache_root
        .join("assets")
        .join(digest(name)?)
        .join(name);
    if !dest.is_file() {
        let parent = dest
            .parent()
            .ok_or_else(|| format!("asset dest has no parent: {}", dest.display()))?;
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        let tmp = parent.join(format!(
            ".{}.tmp.{}",
            dest.file_name().unwrap().to_string_lossy(),
            std::process::id()
        ));
        std::fs::write(&tmp, data).map_err(|e| e.to_string())?;
        std::fs::rename(&tmp, &dest).map_err(|e| e.to_string())?;
    }
    Ok(dest)
}

#[cfg(test)]
mod tests {
    use super::*;

    // Pinned sha256 of the shipped bytes (independently: `sha256sum`). The same
    // constants are asserted by the Python store's test, so a three-way match
    // (sha256sum, Rust, Python) proves cross-engine digest identity. Regenerate
    // when a helper is migrated/edited.
    const JAVAC_WORKER_SHA: &str =
        "f274836d48914a0cb7597076c170aa9ef7904f41d745efe33716af427a6c28e8";

    #[test]
    fn embeds_the_tree() {
        assert!(!EMBEDDED.is_empty(), "assets/ must embed at least one helper");
        assert!(bytes("java/JavacWorker.java").is_some());
    }

    #[test]
    fn digest_is_pinned_byte_hash() {
        assert_eq!(digest("java/JavacWorker.java").unwrap(), JAVAC_WORKER_SHA);
    }

    #[test]
    fn unknown_name_is_a_loud_error() {
        assert!(digest("java/Nope.java").is_err());
        let tmp = std::env::temp_dir();
        assert!(resolve_path("java/Nope.java", &tmp).is_err());
    }

    #[test]
    fn resolve_materializes_exact_bytes_and_is_path_independent() {
        let a = tempdir();
        let b = tempdir();
        let pa = resolve_path("java/JavacWorker.java", &a).unwrap();
        let pb = resolve_path("java/JavacWorker.java", &b).unwrap();
        // Different roots -> different paths, identical bytes.
        assert_ne!(pa, pb);
        let ba = std::fs::read(&pa).unwrap();
        assert_eq!(ba, bytes("java/JavacWorker.java").unwrap());
        assert_eq!(std::fs::read(&pb).unwrap(), ba);
        // ...and the digest never depended on which root we rendered into.
        assert_eq!(digest("java/JavacWorker.java").unwrap(), JAVAC_WORKER_SHA);
    }

    fn tempdir() -> PathBuf {
        use std::sync::atomic::{AtomicUsize, Ordering};
        static N: AtomicUsize = AtomicUsize::new(0);
        let p = std::env::temp_dir().join(format!(
            "brix-assets-test-{}-{}",
            std::process::id(),
            N.fetch_add(1, Ordering::Relaxed)
        ));
        std::fs::create_dir_all(&p).unwrap();
        p
    }
}
