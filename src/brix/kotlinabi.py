"""The ``kotlin-abi`` content identity: jvm-abi, except inline counts by bytes.

Kotlin copies ``inline fun`` bodies into *consumers'* bytecode — together with
their line-number tables (for SMAP debugging) and any lambdas or anonymous
objects declared inside them (kotlinc regenerates those into the consumer from
the dependency's compiled classes). So for a Kotlin dependency, "the ABI is
the interface" is false exactly where inline is involved: an implementation
edit — even a comment added *above* an inline function, which only shifts line
numbers — legitimately changes a dependent's output. This lens keeps the
jvm-abi skip everywhere it is sound and switches to whole-class byte hashing
exactly where it is not. Per class in a jar:

- no Kotlin ``@Metadata`` annotation (plain Java) → jvm-abi class digest;
- Kotlin metadata declaring **no** inline function and **no** inline property
  accessor → jvm-abi class digest (the recovered cross-module skip);
- any inline member, **or** nesting under such a class (a ``$``-prefixed
  binary name — lambdas/objects regenerated by inlining live there), **or**
  metadata this parser cannot confidently read → the class's byte hash.

Fail closed: every anomaly — unknown metadata kind or version, the legacy
8-to-7 string packing, protobuf oddities like the pre-1.0 ``old_flags``
field — makes the class count by bytes. Wrong in the slow direction, never
stale. ``const val`` needs no special handling here: it compiles to a
``static final`` field with a ``ConstantValue`` attribute, which jvm-abi
already includes; ``reified`` requires ``inline``, so it is covered.

Format facts are pinned from the Kotlin compiler's own sources
(``core/metadata/src/metadata.proto``, ``.../deserialization/Flags.java``,
``core/metadata.jvm/.../BitEncoding.java``) and verified against
kotlinc-compiled fixtures (tests/fixtures/kotlinabi/):

- ``@Metadata.d1`` strings are BitEncoding-packed: first char ``\\u0000``
  marks UTF-8 mode → drop the marker, each remaining char is one byte;
- the payload is a varint-delimited ``StringTableTypes`` message followed by
  a ``Class`` (kind 1) or ``Package`` (kinds 2 and 5) protobuf message;
- ``Class.function = 9``, ``Class.property = 10``; ``Package.function = 3``,
  ``Package.property = 4``;
- ``Function.flags = 9`` with IS_INLINE at bit 10; ``Property.getter_flags =
  7`` / ``setter_flags = 8`` with IS_INLINE_ACCESSOR at bit 8 (absent
  accessor flags mean "not inline", per metadata.proto).

Like jvm-abi, this digest is a cross-machine cache key: the Rust core mirrors
it byte-for-byte (rust/brix-core/src/lenses/kotlinabi.rs) and this module is
the reference implementation. A ``version`` bump in one must land in both.
"""

from __future__ import annotations

import hashlib
import zipfile
from pathlib import Path

from . import jvmabi

# kotlin.Metadata's type descriptor and element names, in the canonical
# hex-of-utf8 form jvmabi.class_abi uses for annotation payloads.
_METADATA_TYPE = b"Lkotlin/Metadata;".hex()
_ELEM_K = b"k".hex()
_ELEM_MV = b"mv".hex()
_ELEM_D1 = b"d1".hex()

# @Metadata kinds (kotlin.Metadata.kind).
_KIND_CLASS = 1
_KIND_FILE_FACADE = 2
_KIND_SYNTHETIC = 3
_KIND_MULTIFILE_FACADE = 4
_KIND_MULTIFILE_PART = 5

# Metadata major versions this parser is calibrated against (kotlinx-metadata
# reads the same range). Anything else → byte hash.
_SUPPORTED_MAJORS = (1, 2)

_FUNCTION_IS_INLINE = 1 << 10  # Flags.java: ...IS_INFIX, IS_INLINE, IS_TAILREC...
_ACCESSOR_IS_INLINE = 1 << 8  # Flags.java: IS_NOT_DEFAULT, IS_EXTERNAL, IS_INLINE

_INTEGER = 3  # constant-pool tag inside canonical primitive element values


class _Unparseable(Exception):
    """Metadata we will not vouch for — the class falls back to byte hashing."""


# -- @Metadata extraction from the canonical class ABI ------------------------


def _metadata_elements(abi: dict) -> dict | None:
    """The @Metadata annotation's elements, or None for a non-Kotlin class."""
    for type_hex, pairs in abi.get("annotations", []):
        if type_hex == _METADATA_TYPE:
            return {name: value for name, value in pairs}
    return None


def _int_element(value) -> int:
    # Canonical form of an int-valued element: ["I", [INTEGER_TAG, n]].
    if (
        isinstance(value, list)
        and len(value) == 2
        and value[0] == "I"
        and isinstance(value[1], list)
        and len(value[1]) == 2
        and value[1][0] == _INTEGER
    ):
        return value[1][1]
    raise _Unparseable("malformed int element in @Metadata")


def _int_array_element(value) -> list[int]:
    if not (isinstance(value, list) and len(value) == 2 and value[0] == "["):
        raise _Unparseable("malformed int array in @Metadata")
    return [_int_element(v) for v in value[1]]


def _string_array_bytes(value) -> list[bytes]:
    """A String-array element's strings, as raw modified-UTF-8 bytes."""
    if not (isinstance(value, list) and len(value) == 2 and value[0] == "["):
        raise _Unparseable("malformed string array in @Metadata")
    out = []
    for v in value[1]:
        if not (isinstance(v, list) and len(v) == 2 and v[0] == "s"):
            raise _Unparseable("malformed string element in @Metadata")
        out.append(bytes.fromhex(v[1]))
    return out


def _mutf8_chars(data: bytes) -> list[int]:
    """Modified UTF-8 (JVMS 4.4.7) to UTF-16 code units."""
    out = []
    i, n = 0, len(data)
    while i < n:
        b = data[i]
        if 0x01 <= b <= 0x7F:
            out.append(b)
            i += 1
        elif 0xC0 <= b <= 0xDF and i + 1 < n and data[i + 1] & 0xC0 == 0x80:
            out.append(((b & 0x1F) << 6) | (data[i + 1] & 0x3F))
            i += 2
        elif (
            0xE0 <= b <= 0xEF
            and i + 2 < n
            and data[i + 1] & 0xC0 == 0x80
            and data[i + 2] & 0xC0 == 0x80
        ):
            out.append(((b & 0x0F) << 12) | ((data[i + 1] & 0x3F) << 6) | (data[i + 2] & 0x3F))
            i += 3
        else:
            raise _Unparseable("invalid modified UTF-8 in @Metadata")
    return out


def _decode_d1(strings: list[bytes]) -> bytes:
    """BitEncoding.decodeBytes, UTF-8 mode only (the modern encoding): drop
    the ``\\u0000`` marker, then every char is one byte. The legacy 8-to-7
    packing (marker ``\\uffff``) is not vouched for."""
    if not strings:
        raise _Unparseable("empty d1")
    chars = [_mutf8_chars(s) for s in strings]
    if not chars[0] or chars[0][0] != 0x0000:
        raise _Unparseable("d1 is not UTF-8-mode BitEncoding")
    flat = chars[0][1:] + [c for s in chars[1:] for c in s]
    if any(c > 0xFF for c in flat):
        raise _Unparseable("d1 char out of byte range")
    return bytes(flat)


# -- just enough protobuf to find the inline flags -----------------------------


class _Proto:
    __slots__ = ("d", "p", "end")

    def __init__(self, data: bytes) -> None:
        self.d = data
        self.p = 0
        self.end = len(data)

    def at_end(self) -> bool:
        return self.p >= self.end

    def varint(self) -> int:
        result = 0
        shift = 0
        while True:
            if self.p >= self.end:
                raise _Unparseable("truncated varint")
            b = self.d[self.p]
            self.p += 1
            result |= (b & 0x7F) << shift
            if not b & 0x80:
                return result
            shift += 7
            if shift > 63:
                raise _Unparseable("varint too long")

    def advance(self, n: int) -> None:
        if n < 0 or self.p + n > self.end:
            raise _Unparseable("truncated field")
        self.p += n

    def bytes_field(self) -> bytes:
        n = self.varint()
        if self.p + n > self.end:
            raise _Unparseable("truncated bytes field")
        b = self.d[self.p : self.p + n]
        self.p += n
        return b

    def skip(self, wire: int) -> None:
        if wire == 0:
            self.varint()
        elif wire == 1:
            self.advance(8)
        elif wire == 2:
            self.advance(self.varint())
        elif wire == 5:
            self.advance(4)
        else:  # groups (3/4) or garbage: metadata.proto uses neither
            raise _Unparseable(f"unsupported wire type {wire}")


def _function_is_inline(data: bytes) -> bool:
    """ProtoBuf.Function: flags = 9. A message carrying only the pre-1.0
    ``old_flags`` (field 1, different bit layout) is not vouched for."""
    r = _Proto(data)
    flags = None
    saw_old_flags = False
    while not r.at_end():
        key = r.varint()
        field, wire = key >> 3, key & 7
        if field == 9 and wire == 0:
            flags = r.varint()
        elif field == 1 and wire == 0:
            saw_old_flags = True
            r.varint()
        else:
            r.skip(wire)
    if flags is None and saw_old_flags:
        raise _Unparseable("pre-1.0 old_flags function metadata")
    return flags is not None and bool(flags & _FUNCTION_IS_INLINE)


def _property_has_inline_accessor(data: bytes) -> bool:
    """ProtoBuf.Property: getter_flags = 7, setter_flags = 8; absent accessor
    flags mean "not inline" by definition (metadata.proto). ``old_flags``
    without the modern ``flags`` (field 11) is not vouched for."""
    r = _Proto(data)
    inline = False
    flags = None
    saw_old_flags = False
    while not r.at_end():
        key = r.varint()
        field, wire = key >> 3, key & 7
        if field in (7, 8) and wire == 0:
            inline = inline or bool(r.varint() & _ACCESSOR_IS_INLINE)
        elif field == 11 and wire == 0:
            flags = r.varint()
        elif field == 1 and wire == 0:
            saw_old_flags = True
            r.varint()
        else:
            r.skip(wire)
    if flags is None and saw_old_flags:
        raise _Unparseable("pre-1.0 old_flags property metadata")
    return inline


def _payload_has_inline(kind: int, d1: bytes) -> bool:
    """Scan a Class (kind 1) or Package (kinds 2/5) message for any inline
    function or inline property accessor."""
    r = _Proto(d1)
    r.advance(r.varint())  # the varint-delimited StringTableTypes message
    if kind == _KIND_CLASS:
        fn_field, prop_field = 9, 10
    else:  # file facade / multifile part: a Package message
        fn_field, prop_field = 3, 4
    while not r.at_end():
        key = r.varint()
        field, wire = key >> 3, key & 7
        if field == fn_field and wire == 2:
            if _function_is_inline(r.bytes_field()):
                return True
        elif field == prop_field and wire == 2:
            if _property_has_inline_accessor(r.bytes_field()):
                return True
        else:
            r.skip(wire)
    return False


# -- per-class mode ------------------------------------------------------------


def _class_mode(abi: dict) -> str:
    """``"abi"`` or ``"raw"``, from the class's own metadata. Nesting under an
    inline-carrying class is the jar level's job (`digest_jar`)."""
    elements = _metadata_elements(abi)
    if elements is None:
        return "abi"  # not a Kotlin class: jvm-abi semantics are sound
    try:
        mv = _int_array_element(elements[_ELEM_MV])
        if not mv or mv[0] not in _SUPPORTED_MAJORS:
            raise _Unparseable("uncalibrated metadata version")
        kind = _int_element(elements[_ELEM_K])
        if kind == _KIND_SYNTHETIC:
            # Lambdas, DefaultImpls, WhenMappings: no member list of their
            # own. Consumers only read them via inlining, and then they nest
            # under the inline-carrying class — the jar level catches that.
            return "abi"
        if kind in (_KIND_CLASS, _KIND_FILE_FACADE, _KIND_MULTIFILE_PART):
            d1 = _decode_d1(_string_array_bytes(elements[_ELEM_D1]))
            return "raw" if _payload_has_inline(kind, d1) else "abi"
        # Multifile facades (kind 4) and anything newer: not vouched for.
        raise _Unparseable(f"unhandled metadata kind {kind!r}")
    except (_Unparseable, KeyError):
        return "raw"  # fail closed: count by bytes, never go stale


def _enclosed_in(name: bytes, flagged: set[bytes]) -> bool:
    """Is any ``$``-prefix ancestor of this binary name flagged? Nested and
    synthetic classes (``Outer$Inner``, ``CoreKt$combine$1``) carry the
    declaring class's name as a prefix."""
    i = name.rfind(b"$")
    while i > 0:
        if name[:i] in flagged:
            return True
        i = name.rfind(b"$", 0, i)
    return False


def _class_facts(data: bytes) -> tuple[bytes, str, dict]:
    """(binary name, own mode, canonical ABI) for one class file."""
    abi = jvmabi.class_abi(data)
    name_hex = abi.get("name")
    name = bytes.fromhex(name_hex) if name_hex else b""
    return name, _class_mode(abi), abi


def _part(name: bytes, mode: str, digest: str) -> str:
    return f"{name.hex()}:{mode}:{digest}"


def _raw_digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# -- digests -------------------------------------------------------------------


def digest_class(data: bytes) -> str:
    """kotlin-abi digest of a single class file. Without a jar for context, a
    ``$``-nested name could be a lambda regenerated from an inline body, so it
    counts by bytes."""
    name, mode, abi = _class_facts(data)
    if mode == "abi" and b"$" in name:
        mode = "raw"
    digest = jvmabi._digest_bytes(abi) if mode == "abi" else _raw_digest(data)
    return _raw_digest(_part(name, mode, digest).encode())


def digest_jar(path: Path) -> str:
    """kotlin-abi digest of a jar. Two passes: decide each class's own mode,
    then flow ``raw`` down to everything nested under a flagged name. Also
    counts ``META-INF/*.kotlin_module`` entries (multifile/package-part
    tables the compiler reads) by bytes; other resources are ignored, as in
    jvm-abi."""
    classes = []
    modules = []
    flagged: set[bytes] = set()
    with zipfile.ZipFile(path) as zf:
        for entry in sorted(zf.namelist()):
            if entry.endswith(".class"):
                data = zf.read(entry)
                name, mode, abi = _class_facts(data)
                classes.append((name, mode, abi, _raw_digest(data)))
                if mode == "raw":
                    flagged.add(name)
            elif entry.startswith("META-INF/") and entry.endswith(".kotlin_module"):
                modules.append(f"module:{_raw_digest(zf.read(entry))}")
    parts = []
    for name, mode, abi, raw in classes:
        if mode == "abi" and _enclosed_in(name, flagged):
            mode = "raw"
        parts.append(_part(name, mode, raw if mode == "raw" else jvmabi._digest_bytes(abi)))
    parts.extend(modules)
    parts.sort()
    return _raw_digest("\n".join(parts).encode())


def digest(path: Path) -> str:
    """kotlin-abi digest of a jar or a single ``.class`` file."""
    path = Path(path)
    if zipfile.is_zipfile(path):
        return digest_jar(path)
    return digest_class(path.read_bytes())
